import torch
from bert_score import Scorer


class CommentEvaluator:
    """
    Evaluates the quality of generated code review comments against human references.
    Primary metric: BERTScore using CodeBERT.
    """
    def __init__(self, model_type="microsoft/codebert-base", lang="en"):
        print(f"Loading Evaluator with model: {model_type}...")
        self.scorer = Scorer(model_type=model_type, lang=lang, rescale_with_baseline=True)

    def compute_quality(self, predictions, references):
        """
        Args:
            predictions (list of str): Comments generated by our AI.
            references (list of str): Original comments written by humans.

        Returns:
            dict: Mean Precision, Recall, and F1 scores.
        """
        if not predictions or not references:
            return {"error": "Empty input lists"}

        # Calculate BERTScore
        P, R, F1 = self.scorer.score(predictions, references)

        # Return the average scores as standard Python floats
        return {
            "precision": P.mean().item(),
            "recall": R.mean().item(),
            "f1": F1.mean().item()
        }


if __name__ == "__main__":
    hyps = ["You should remove this unused variable to clean up the code."]
    refs = ["Unused variable detected. Recommended to delete it."]

    evaluator = CommentEvaluator()
    results = evaluator.compute_quality(hyps, refs)

    print("\nEvaluation Results")
    for metric, value in results.items():
        print(f"{metric.capitalize()}: {value:.4f}")
